export const erpDocTotals = (() => {
  const totals = { total: 0, linked: 0, unlinked: 0, lost: 0 }
  Object.values(erpDocs).forEach((records) => {
    records.forEach((record) => {
      totals.total += 1
      if (record.link.status === '已关联') {
        totals.linked += 1
      } else if (record.link.status === '未关联') {
        totals.unlinked += 1
      } else if (record.link.status === '已失联') {
        totals.lost += 1
      }
    })
  })
  return totals
})()
